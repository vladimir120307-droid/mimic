import 'package:flutter/material.dart';
import 'screens/catalog_screen.dart';
import 'screens/product_screen.dart';

void main() => runApp(const MimicApp());

class MimicApp extends StatelessWidget {
  const MimicApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Generated by mimic',
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        useMaterial3: true,
        colorScheme: ColorScheme.fromSeed(
          seedColor: const Color(0xFFE11D48),
          brightness: Brightness.light,
        ),
      ),
      initialRoute: '/',
      routes: {
        '/': (context) => const CatalogScreen(),
        "/catalog": (context) => const CatalogScreen(),
        "/product_detail": (context) => const ProductScreen(),
      },
    );
  }
}
