import 'package:flutter/material.dart';
import 'screens/month_screen.dart';
import 'screens/event__detail_screen.dart';

void main() => runApp(const MimicApp());

class MimicApp extends StatelessWidget {
  const MimicApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Generated by mimic',
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        useMaterial3: true,
        colorScheme: ColorScheme.fromSeed(
          seedColor: const Color(0xFF10B981),
          brightness: Brightness.light,
        ),
      ),
      initialRoute: '/',
      routes: {
        '/': (context) => const MonthScreen(),
        "/month": (context) => const MonthScreen(),
        "/event_detail": (context) => const Event DetailScreen(),
      },
    );
  }
}
